#!/usr/bin/env node
/**
 * Przed build:sim — wpisuje IP Maca (en0/en1), żeby iOS Simulator trafił w API na hoście.
 * Plik generowany; domyślnie null gdy brak sieci.
 */
import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'src/environments/simulator-api-host.ts');

function lanIp() {
  for (const iface of ['en0', 'en1']) {
    try {
      const ip = execSync(`ipconfig getifaddr ${iface}`, { encoding: 'utf8' }).trim();
      if (ip) return ip;
    } catch {
      /* brak interfejsu */
    }
  }
  return null;
}

const ip = lanIp();
const origin = ip ? `http://${ip}:8000` : null;
const body = `/** Auto-generated by scripts/sync-simulator-api-host.mjs — nie edytuj ręcznie */
export const SIMULATOR_API_ORIGIN: string | null = ${origin ? `'${origin}'` : 'null'};
`;

if (!fs.existsSync(out)) {
  fs.mkdirSync(path.dirname(out), { recursive: true });
}
fs.writeFileSync(out, body, 'utf8');
console.log(`simulator API origin: ${origin ?? '(null — używany fallback z environment)'}`);
